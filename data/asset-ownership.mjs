const rentekSet = new Set(RENTEK_SERIALS.split('\n'));
const biaSet    = new Set(BIA_SERIALS.split('\n'));

export function normalizeSerial(serial) {
  return String(serial || '').replace(/[^A-Za-z0-9]/g, '').toUpperCase();
}

/** 'RENTEK' | 'BIA' | null (null = sin serial o no está en el listado) */
export function getAssetOwnership(serial) {
  const key = normalizeSerial(serial);
  if (!key) return null;
  if (rentekSet.has(key)) return 'RENTEK';
  if (biaSet.has(key)) return 'BIA';

  // Algunos sistemas recortan los ceros a la izquierda del serial.
  const sinCeros = key.replace(/^0+/, '');
  if (sinCeros && sinCeros !== key) {
    if (rentekSet.has(sinCeros)) return 'RENTEK';
    if (biaSet.has(sinCeros)) return 'BIA';
  }
  return null;
}

